#!/usr/bin/env bash
# init-signing.sh — set up local release signing for a fresh clone.
#
# What it does:
#   1. Ensures a .env exists (copies from .env.example on first run).
#   2. Generates a self-signed release keystore via keytool if one isn't present.
#   3. Writes keystore.properties so `./gradlew :app:assembleRelease` produces a signed APK.
#
# Everything it creates (.env, the keystore, keystore.properties) is gitignored. This is a
# personal sideloaded app — the key protects nothing remote; it only pins the app's update
# identity. See README.md and docs/DESIGN.md §3.
set -euo pipefail

cd "$(dirname "$0")/.."   # repo root

# --- 1. .env -------------------------------------------------------------------------
if [[ ! -f .env ]]; then
  cp .env.example .env
  echo "Created .env from .env.example — edit it to set your own signing passwords."
fi

# Load .env (export every assignment).
set -a
# shellcheck disable=SC1091
. ./.env
set +a

KEYSTORE_FILE="${RELEASE_KEYSTORE_FILE:-photoframe-release.keystore}"
STORE_PASS="${RELEASE_STORE_PASSWORD:?set RELEASE_STORE_PASSWORD in .env}"
KEY_PASS="${RELEASE_KEY_PASSWORD:?set RELEASE_KEY_PASSWORD in .env}"
KEY_ALIAS="${RELEASE_KEY_ALIAS:?set RELEASE_KEY_ALIAS in .env}"
KEY_DNAME="${RELEASE_KEY_DNAME:-CN=Photo Frame, OU=Personal, O=Photo Frame, C=US}"

if [[ "$STORE_PASS" == "changeme" || "$KEY_PASS" == "changeme" ]]; then
  echo "WARNING: signing passwords are still 'changeme' in .env — using them anyway." >&2
fi

# --- 2. keystore ---------------------------------------------------------------------
if [[ -f "$KEYSTORE_FILE" ]]; then
  echo "Keystore already exists: $KEYSTORE_FILE (leaving it untouched)."
else
  command -v keytool >/dev/null || { echo "keytool not found — install a JDK 17." >&2; exit 1; }
  echo "Generating self-signed release keystore: $KEYSTORE_FILE"
  keytool -genkeypair \
    -keystore "$KEYSTORE_FILE" \
    -alias "$KEY_ALIAS" \
    -storepass "$STORE_PASS" \
    -keypass "$KEY_PASS" \
    -dname "$KEY_DNAME" \
    -keyalg RSA -keysize 2048 -validity 10000
fi

# --- 3. keystore.properties ----------------------------------------------------------
cat > keystore.properties <<EOF
# Generated by scripts/init-signing.sh — gitignored, never commit.
storeFile=$KEYSTORE_FILE
storePassword=$STORE_PASS
keyAlias=$KEY_ALIAS
keyPassword=$KEY_PASS
EOF

echo "Wrote keystore.properties. You can now run: ./gradlew :app:assembleRelease"
